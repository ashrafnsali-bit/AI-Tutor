import type { Assessment, GradeLevel, Lecture, LectureDiagram, Question, Subject } from '../types';
import { SAUDI_PRIMARY_ARABIC_G5_LECTURES } from './saudiPrimaryArabic5CurriculumData';

interface ArabicLessonSpec {
  titleAr: string;
  titleEn: string;
  unitAr: string;
  summaryAr: string;
  summaryEn: string;
  exampleAr: string;
  exampleEn: string;
  diagramTitleAr: string;
  diagramTitleEn: string;
  diagramCaptionAr: string;
  diagramCaptionEn: string;
  stepsAr: string[];
  stepsEn: string[];
  checkAr: string;
  isTrue: boolean;
  feedbackAr: string;
  feedbackEn: string;
  sourcePagesAr?: string;
  sourcePagesEn?: string;
}

interface GradeCourse {
  grade: GradeLevel;
  subject: 'PRIMARY_ARABIC' | 'ARABIC_LANG' | 'ARABIC_LIT';
  gradeNameAr: string;
  gradeNameEn: string;
  courseNameAr: string;
  courseNameEn: string;
  sourceNoteAr?: string;
  sourceNoteEn?: string;
  lessons: ArabicLessonSpec[];
}

function makeDiagram(grade: GradeLevel, order: number, spec: ArabicLessonSpec): LectureDiagram {
  return {
    id: `sa-${grade.toLowerCase()}-arabic-figure-${order}`,
    figureNumberAr: `شكل ${order}`,
    figureNumberEn: `Figure ${order}`,
    titleAr: spec.diagramTitleAr,
    titleEn: spec.diagramTitleEn,
    captionAr: spec.diagramCaptionAr,
    captionEn: spec.diagramCaptionEn,
    diagramType: 'arabic_learning_map',
    visualSteps: spec.stepsAr.map((labelAr, index) => ({
      labelAr,
      labelEn: spec.stepsEn[index] || labelAr
    }))
  };
}

function makeAssessment(grade: GradeLevel, order: number, spec: ArabicLessonSpec): Assessment {
  const question: Question = {
    id: `sa-${grade.toLowerCase()}-ar-${order}-check`,
    textAr: spec.checkAr,
    textEn: `True or false: ${spec.summaryEn}`,
    optionsAr: ['صحيح', 'غير صحيح'],
    optionsEn: ['True', 'False'],
    correctIndex: spec.isTrue ? 0 : 1,
    conceptTestedAr: spec.titleAr,
    conceptTestedEn: spec.titleEn,
    explanationAr: spec.feedbackAr,
    explanationEn: spec.feedbackEn,
    difficulty: 'easy'
  };

  return {
    id: `sa-${grade.toLowerCase()}-ar-${order}-assessment`,
    titleAr: `تحقق من الفهم: ${spec.titleAr}`,
    titleEn: `Check your understanding: ${spec.titleEn}`,
    passingScore: 80,
    questions: [question]
  };
}

function buildCourse(course: GradeCourse): Lecture[] {
  return course.lessons.map((spec, index) => {
    const order = index + 1;
    const diagram = makeDiagram(course.grade, order, spec);

    return {
      id: `sa-${course.grade.toLowerCase()}-${course.subject.toLowerCase()}-${order}`,
      order,
      titleAr: spec.titleAr,
      titleEn: spec.titleEn,
      subtitleAr: spec.summaryAr,
      subtitleEn: spec.summaryEn,
      durationMinutes: Number(course.grade.slice(1)) <= 3 ? 20 : 30,
      isLocked: index > 0,
      isCompleted: false,
      passingScoreRequired: 80,
      country: 'SA',
      subject: course.subject,
      gradeLevel: course.grade,
      educationType: 'PUBLIC',
      educationTrack: 'GENERAL',
      descriptionAr: course.sourceNoteAr
        ? `${course.sourceNoteAr}${spec.sourcePagesAr ? ` نطاق المحتوى في الكتاب: ${spec.sourcePagesAr}.` : ''}`
        : undefined,
      descriptionEn: course.sourceNoteEn
        ? `${course.sourceNoteEn}${spec.sourcePagesEn ? ` Textbook pages: ${spec.sourcePagesEn}.` : ''}`
        : undefined,
      gradeLevelNameAr: `${course.gradeNameAr} - ${course.courseNameAr}`,
      gradeLevelNameEn: `${course.gradeNameEn} - ${course.courseNameEn}`,
      ministryAr: 'وزارة التعليم بالمملكة العربية السعودية',
      ministryEn: 'Ministry of Education - Kingdom of Saudi Arabia',
      unitTitleAr: spec.unitAr,
      unitTitleEn: `${course.courseNameEn}: curriculum skills`,
      lessonNumberAr: ['G10', 'G11'].includes(course.grade) ? `الكفاية ${order}` : `المهارة ${order}`,
      lessonNumberEn: ['G10', 'G11'].includes(course.grade) ? `Competency ${order}` : `Skill ${order}`,
      warmupHookAr: spec.exampleAr,
      warmupHookEn: spec.exampleEn,
      learningOutcomesAr: [spec.summaryAr],
      learningOutcomesEn: [spec.summaryEn],
      keyConceptsAr: [spec.summaryAr],
      keyConceptsEn: [spec.summaryEn],
      summaryAr: spec.summaryAr,
      summaryEn: spec.summaryEn,
      sections: [
        {
          titleAr: 'خريطة الدرس',
          titleEn: 'Lesson map',
          contentAr: spec.summaryAr,
          contentEn: spec.summaryEn,
          diagram
        },
        {
          titleAr: 'مثال وتطبيق',
          titleEn: 'Example and practice',
          contentAr: spec.exampleAr,
          contentEn: spec.exampleEn
        }
      ],
      assessment: makeAssessment(course.grade, order, spec)
    };
  });
}

