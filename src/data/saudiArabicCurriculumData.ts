export function getSaudiArabicCurriculum(gradeLevel: GradeLevel, subject: Subject): Lecture[] | undefined {
  if (gradeLevel === 'G5' && subject === 'PRIMARY_ARABIC') {
    return SAUDI_PRIMARY_ARABIC_G5_LECTURES;
  }
  const course = SAUDI_ARABIC_COURSES[gradeLevel];
  return course?.subject === subject ? buildCourse(course) : undefined;
}
