const createScienceLecture = (course: CourseSpec, lesson: SaudiScienceLesson, index: number): Lecture => {
  const courseId = course.idPrefix ?? `sa-science-${course.gradeLevel.toLowerCase()}-${course.subject.toLowerCase()}`;
  const lectureId = `${courseId}-${index + 1}`;
  const pageReferenceAr = lesson.pages ? `مرجع المكوّن في الفهرس: ص ${lesson.pages}.\n\n` : '';
  const pageReferenceEn = lesson.pages ? `Contents page reference: p. ${lesson.pages}.\n\n` : '';
  const question: Question = {
    id: `${lectureId}-q1`,
    textAr: lesson.questionAr,
    textEn: lesson.questionEn,
    optionsAr: lesson.optionsAr,
    optionsEn: lesson.optionsEn,
    correctIndex: lesson.correctIndex,
    conceptTestedAr: lesson.unitAr,
    conceptTestedEn: lesson.unitEn,
    explanationAr: lesson.explanationAr,
    explanationEn: lesson.explanationEn,
    difficulty: 'easy'
  };
  const visualSteps: LectureDiagramStep[] = lesson.stepsAr.map((labelAr, stepIndex) => ({
    labelAr,
    labelEn: lesson.stepsEn[stepIndex]
  }));
  const section: LectureSection = {
    titleAr: lesson.titleAr,
    titleEn: lesson.titleEn,
    contentAr: `${lesson.conceptsAr.join('\n\n')}\n\n${pageReferenceAr}${course.sourceNoteAr ?? 'هذا شرح تعليمي أصلي موجز لمفاهيم العلوم المناسبة للصف، وليس نقلًا حرفيًا من كتاب مدرسي. لم تتوفر نسخة قابلة للتحقق من كتاب العلوم الرسمي أثناء الإعداد؛ لذا فهذا المسار داعم ولم تطابق عناوينه مع فهرس طبعة وزارة بعينها.'}`,
    contentEn: `${lesson.conceptsEn.join('\n\n')}\n\n${pageReferenceEn}${course.sourceNoteEn ?? 'This is an original concise explanation of grade-appropriate science concepts, not a verbatim textbook excerpt. An accessible official science textbook edition could not be verified during preparation, so this supplementary path has not been cross-checked against a specific Ministry contents page.'}`,
    diagram: {
      id: lesson.unitNumber === undefined
        ? `${lectureId}-visual`
        : `${lectureId}-unit-${lesson.unitNumber}-visual`,
      figureNumberAr: `شكل (${index + 1})`,
      figureNumberEn: `Figure (${index + 1})`,
      titleAr: `رسم علمي توضيحي: ${lesson.titleAr}`,
      titleEn: `Science illustration: ${lesson.titleEn}`,
      captionAr: 'رسم تعليمي أصلي من المنصة يوضح الفكرة العلمية؛ ليس صورة من كتاب الوزارة.',
      captionEn: 'An original platform learning illustration of the science concept, not an image from a Ministry textbook.',
      diagramType: lesson.diagramType,
      visualSteps
    }
  };

  return {
    id: lectureId,
    order: index + 1,
    titleAr: lesson.titleAr,
    titleEn: lesson.titleEn,
    subtitleAr: lesson.unitAr,
    subtitleEn: lesson.unitEn,
    durationMinutes: 30,
    isLocked: false,
    isCompleted: false,
    passingScoreRequired: 80,
    gradeLevelNameAr: `الصف ${course.gradeLevel.slice(1)} – ${course.courseNameAr} (المملكة العربية السعودية${course.editionAr ? ` – ${course.editionAr}` : ' – محتوى داعم'})`,
    gradeLevelNameEn: `Grade ${course.gradeLevel.slice(1)} – ${course.courseNameEn} (Saudi Arabia${course.editionEn ? ` – ${course.editionEn}` : ' – supplementary content'})`,
    termAr: course.termAr ?? 'دروس العلوم حسب المرحلة والصف',
    termEn: course.termEn ?? 'Grade-level science lessons',
    unitTitleAr: lesson.unitAr,
    unitTitleEn: lesson.unitEn,
    lessonNumberAr: lesson.lessonNumberAr ?? `الدرس ${index + 1}`,
    lessonNumberEn: lesson.lessonNumberEn ?? `Lesson ${index + 1}`,
    keyConceptsAr: lesson.conceptsAr,
    keyConceptsEn: lesson.conceptsEn,
    summaryAr: lesson.conceptsAr.join(' '),
    summaryEn: lesson.conceptsEn.join(' '),
    sections: [section],
    assessment: {
      id: `${lectureId}-assessment`,
      lectureId,
      titleAr: `تقويم: ${lesson.titleAr}`,
      titleEn: `Check: ${lesson.titleEn}`,
      passingScore: 80,
      questions: [question]
    }
  };
};

export const SAUDI_SCIENCE_CURRICULA: Partial<Record<GradeLevel, Partial<Record<Subject, Lecture[]>>>> = {};

for (const course of lessonsByGrade) {
  SAUDI_SCIENCE_CURRICULA[course.gradeLevel] ??= {};
  SAUDI_SCIENCE_CURRICULA[course.gradeLevel]![course.subject] = course.lessons.map((lesson, index) =>
    createScienceLecture(course, lesson, index)
  );
}
