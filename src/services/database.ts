/**
 * Stores a newly generated or accredited lecture in the public database so all students
 * in the same country, subject, and grade benefit from it.
 */
export async function saveSharedCurriculumLecture(
  lecture: Lecture,
  country: CountryCode = 'SA',
  subject: Subject = 'MATH',
  gradeLevel: GradeLevel = 'G12'
): Promise<void> {
  const record: Lecture & { isSharedCommunity: boolean; savedAt: number } = {
    ...lecture,
    country,
    isSharedCommunity: true,
    savedAt: Date.now()
  };

  // 1. Save to IndexedDB
  try {
    const db = await getDB();
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(SHARED_LECTURES_STORE, 'readwrite');
      tx.objectStore(SHARED_LECTURES_STORE).put(record);
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error);
    });
  } catch { /* ignore */ }

  // 2. Synchronize to LocalStorage shared arrays
  const countryKey = `TEACHER_AI_SHARED_LECS_${country}_${subject}_${gradeLevel}`;
  const generalKey = `TEACHER_AI_SHARED_LECS_${subject}`;

  [countryKey, generalKey].forEach(k => {
    try {
      const list = JSON.parse(localStorage.getItem(k) || '[]') as Lecture[];
      const idx = list.findIndex(item => item.id === lecture.id);
      if (idx !== -1) {
        list[idx] = record;
      } else {
        list.push(record);
      }
      localStorage.setItem(k, JSON.stringify(list));
    } catch { /* ignore */ }
  });
}

/**
 * Loads all shared public/generated lectures for a given country, subject, and grade.
 */
export async function loadSharedCurriculumLectures(
  country: CountryCode = 'SA',
  subject: Subject = 'MATH',
  gradeLevel: GradeLevel = 'G12'
): Promise<Lecture[]> {
  let dbLectures: Lecture[] = [];

  // Try IndexedDB first
  try {
    const db = await getDB();
    dbLectures = await new Promise<Lecture[]>((resolve) => {
      const tx = db.transaction(SHARED_LECTURES_STORE, 'readonly');
      const store = tx.objectStore(SHARED_LECTURES_STORE);
      const req = store.getAll();
      req.onsuccess = () => {
        const all = (req.result as Lecture[]) || [];
        const filtered = all.filter(l => 
          (!l.country || l.country === country) &&
          l.id.toLowerCase().includes(subject.toLowerCase().replace('_', ''))
        );
        resolve(filtered);
      };
      req.onerror = () => resolve([]);
    });
  } catch {
    dbLectures = [];
  }

  // Fallback / merge with localStorage
  const countryKey = `TEACHER_AI_SHARED_LECS_${country}_${subject}_${gradeLevel}`;
  const generalKey = `TEACHER_AI_SHARED_LECS_${subject}`;
  const local1 = JSON.parse(localStorage.getItem(countryKey) || '[]') as Lecture[];
  const local2 = JSON.parse(localStorage.getItem(generalKey) || '[]') as Lecture[];

  const combinedMap = new Map<string, Lecture>();
  [...dbLectures, ...local1, ...local2].forEach(l => {
    if (l && l.id) combinedMap.set(l.id, l);
  });

  return Array.from(combinedMap.values());
}

